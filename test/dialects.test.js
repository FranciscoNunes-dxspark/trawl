const { postgres: PG, mysql: MY, sqlserver: MS } = DIALECTS;

test('a connection is SQL Server unless its kind says otherwise; /add --kind takes the usual names', () => {
  assert.equal(dialectOf({ server: 'x' }).kind, 'sqlserver');
  assert.equal(dialectOf({ conn: { kind: 'postgres' } }).kind, 'postgres');
  assert.equal(kindOf('MariaDB'), 'mysql');
  const c = parseAddArgs('shop db.local:5433 shop --kind pg --user app --ssl');
  assert.deepEqual([c.kind, c.auth, c.ssl], ['postgres', 'sql', true]);
  assert.equal(describeConn(c), 'postgres://db.local:5433/shop');
  assert.equal(parseAddArgs('a srv Db --kind sqlserver').kind, undefined);
  assert.throws(() => parseAddArgs('a srv Db --kind mysql'), /--user/);
  assert.throws(() => parseAddArgs('a srv --kind oracle'), /--kind is/);
  assert.deepEqual(hostPort('db.local', 5432), { host: 'db.local', port: 5432 });
  assert.deepEqual(hostPort('db.local,3307', 3306), { host: 'db.local', port: 3307 });
});

test('quoting and the first rows, each the dialect’s way', () => {
  assert.equal(selectTopFor(MS, 'dbo', 'T', 5), 'SELECT TOP (5) * FROM [dbo].[T];');
  assert.equal(selectTopFor(PG, 'public', 'my "t"', 5), 'SELECT * FROM "public"."my ""t""" LIMIT 5;');
  assert.equal(selectTopFor(MY, 'shop', 'or`ders', 5), 'SELECT * FROM `shop`.`or``ders` LIMIT 5;');
  // With a condition (following a key), the WHERE goes before LIMIT.
  assert.equal(PG.selectTop('"public"."t"', 5, '"id" = 1'), 'SELECT * FROM "public"."t" WHERE "id" = 1 LIMIT 5');
  assert.equal(MS.selectTop('[dbo].[T]', 5, '[Id] = 1'), 'SELECT TOP (5) * FROM [dbo].[T] WHERE [Id] = 1');
  const t = { schema: 'public', name: 'clubs', columns: [{ name: 'id', type: 'integer', identity: true, pk: true, nullable: false }] };
  assert.match(createTableScript(t, { foreignKeys: [] }, { quote: PG.quote, identity: PG.identity }), /CREATE TABLE "public"\."clubs" \(\n  "id" integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,\n  PRIMARY KEY \("id"\)/);
  assert.match(definitionSqlFor(MY, { schema: 'shop', name: 'p', kind: 'procedure' }), /^SHOW CREATE PROCEDURE `shop`\.`p`;$/);
  assert.match(definitionSqlFor(PG, { schema: 'public', name: "v'x", kind: 'view' }), /pg_get_viewdef\('"public"\."v''x"'::regclass/);
});

test('scripts split at ; outside strings, comments, quoted names and dollar-quoted bodies', () => {
  const pg = 'SELECT 1;\n-- a; comment\nCREATE FUNCTION f() RETURNS int AS $body$ BEGIN RETURN 1; END $body$ LANGUAGE plpgsql;\n\nSELECT \'a;b\', "c;d"';
  assert.deepEqual(splitScript(pg, PG).map((s) => [s.line, s.text.slice(0, 15)]), [[1, 'SELECT 1'], [2, '-- a; comment\nC'], [5, "SELECT 'a;b', \""]]);
  const my = "SELECT 'it\\'s; here' # a; comment\n;SELECT `x;y` FROM t;";
  assert.deepEqual(splitScript(my, MY).map((s) => s.text), ["SELECT 'it\\'s; here' # a; comment", 'SELECT `x;y` FROM t']);
});

test('Postgres and MySQL statements that write are writes, but REPLACE() is a function', () => {
  assert.equal(classifyScript('COPY t FROM stdin', { dialect: 'postgres' }).write, true);
  assert.equal(classifyScript('CALL refresh_all()', { dialect: 'mysql' }).write, true);
  assert.equal(classifyScript("SELECT REPLACE(name, 'a', 'b') FROM t", { dialect: 'mysql' }).write, false);
  assert.equal(classifyScript('VACUUM t').write, false, 'SQL Server has no VACUUM to worry about');
});

class FakePg extends EventEmitter {
  constructor(answers) {
    super();
    this.answers = answers;
    this.sent = [];
    this.status = 'I';
  }
  async query(config) {
    this.sent.push(config.text);
    const a = this.answers.shift();
    if (a instanceof Error) throw a;
    if (/^BEGIN/i.test(config.text)) this.status = 'T';
    return a;
  }
  getTransactionStatus() {
    return this.status;
  }
  async end() {
    this.emit('end');
  }
}

test('the Postgres adapter runs a statement at a time, cuts at the limit, and says where an error is', async () => {
  const client = new FakePg([
    { command: 'SELECT', fields: [{ name: 'id', dataTypeID: 23 }, { name: 'name', dataTypeID: 25 }], rows: [[1, 'a'], [2, 'b'], [3, 'c']] },
    { command: 'UPDATE', fields: [], rowCount: 2, rows: [] },
  ]);
  const s = postgresSession({ name: 'pg', kind: 'postgres' }, client);
  const res = await s.run('SELECT id, name FROM t;\nUPDATE t SET x = 1', { limit: 2 });
  assert.deepEqual(res.sets[0].columns, [{ name: 'id', type: 'Int' }, { name: 'name', type: 'text' }]);
  assert.deepEqual(res.sets[0].rows, [[1, 'a'], [2, 'b']]);
  assert.equal(res.sets[0].truncated, true);
  assert.equal(res.stopped, true, 'the limit stops the script, as on SQL Server');
  assert.deepEqual(client.sent, ['SELECT id, name FROM t']);
  const failing = new FakePg([{ command: 'BEGIN', fields: [], rows: [] }, Object.assign(new Error('column "nope" does not exist'), { code: '42703', position: '12' })]);
  const t = postgresSession({ name: 'pg', kind: 'postgres' }, failing);
  await assert.rejects(t.run('BEGIN;\n\nSELECT 1,\n  nope FROM t'), (e) => e.line === 4 && e.number === '42703' && Boolean(e.partial));
  assert.equal(await t.tranCount(), 1);
  const cfg = pgConfig({ server: 'h:6543', user: 'u', trustCert: true }, { password: 'pw' });
  assert.deepEqual([cfg.host, cfg.port, cfg.database, cfg.ssl], ['h', 6543, 'postgres', { rejectUnauthorized: false }]);
});

test('the MySQL adapter maps rows and affected counts, follows transactions and USE', async () => {
  const sent = [];
  const answers = [
    [[[1, 'x']], [{ name: 'id', columnType: 3 }, { name: 'v', columnType: 253 }]],
    [{ affectedRows: 3, warningStatus: 0 }, undefined],
    [[], undefined],
  ];
  const c = Object.assign(new EventEmitter(), { query: async ({ sql }) => (sent.push(sql), answers.shift()), end: async () => {} });
  const s = mysqlSession({ name: 'my', kind: 'mysql' }, c, { database: 'a' });
  const res = await s.run('START TRANSACTION; DELETE FROM t WHERE id < 4; USE `b`;');
  assert.deepEqual(res.sets, [{ columns: [{ name: 'id', type: 'Int' }, { name: 'v', type: 'varchar' }], rows: [[1, 'x']], truncated: false }]);
  assert.deepEqual(res.messages, ['3 rows affected']);
  assert.equal(await s.tranCount(), 1);
  assert.equal(s.database, 'b');
  assert.equal(transactionAfter(1, 'COMMIT'), 0);
  assert.equal(transactionAfter(1, 'ROLLBACK TO SAVEPOINT x'), 1);
  assert.equal(transactionAfter(1, 'create table t (x int)'), 0);
  assert.equal(mysqlConfig({ server: 'h', user: 'u' }).port, 3306);
});

test('a MySQL save fails on a statement that doesn’t affect exactly one row, and its transaction is rolled back', async () => {
  const target = { kind: 'mysql', table: { schema: 'shop', name: 't' }, keys: [0], columns: new Map([[0, { name: 'id', type: 'int' }], [1, { name: 'v', type: 'varchar(9)' }]]) };
  const set = { columns: [{ name: 'id' }, { name: 'v' }], rows: [[1, 'a'], [2, 'b']] };
  const changes = { cells: new Map([['0:1', 'x'], ['1:1', 'y']]), deletes: new Set(), inserts: [] };
  const fake = (counts) => {
    const sent = [];
    const c = Object.assign(new EventEmitter(), {
      query: async ({ sql }) => {
        sent.push(sql.replace(/^-- trawl:[^\n]*\n/, ''));
        return [{ affectedRows: /^(-- [^\n]*\n)?UPDATE/.test(sql) ? counts.shift() : 0, warningStatus: 0 }, undefined];
      },
      end: async () => {},
    });
    return { sent, s: mysqlSession({ name: 'my', kind: 'mysql' }, c) };
  };
  // The second row is gone (0 rows): the error says which, and the save's own transaction is rolled back.
  let { sent, s } = fake([1, 0]);
  await assert.rejects(s.run(saveScript(target, set, changes), { recover: saveRecovery(target) }), (e) => /^The row id = 2 changed or is gone/.test(e.message) && e.line === 5);
  assert.deepEqual(sent.map((x) => x.split(' ')[0]), ['START', 'UPDATE', 'UPDATE', 'ROLLBACK']);
  assert.equal(await s.tranCount(), 0);
  // In a transaction already open, back to the savepoint, the transaction still open.
  ({ sent, s } = fake([1, 2]));
  await s.run('START TRANSACTION');
  await assert.rejects(s.run(saveScript(target, set, changes, { transaction: true }), { recover: saveRecovery(target, { transaction: true }) }));
  assert.deepEqual(sent.slice(1), ['SAVEPOINT trawl_edit', "UPDATE `shop`.`t` SET `v` = 'x' WHERE `id` = 1 AND `v` = 'a'", "UPDATE `shop`.`t` SET `v` = 'y' WHERE `id` = 2 AND `v` = 'b'", 'ROLLBACK TO SAVEPOINT trawl_edit', 'RELEASE SAVEPOINT trawl_edit']);
  assert.equal(await s.tranCount(), 1);
  ({ sent, s } = fake([1, 1]));
  const ok = await s.run(saveScript(target, set, changes), { recover: saveRecovery(target) });
  assert.deepEqual(ok.messages, ['0 rows affected', '1 row affected', '1 row affected', '0 rows affected']);
  assert.equal(sent.at(-1), 'COMMIT');
  // An UPDATE counts the rows it finds, even those it leaves as they were.
  assert.deepEqual(mysqlConfig({ server: 'h', user: 'u' }).flags, ['FOUND_ROWS']);
});

test('a Postgres run that fails runs its recover statements before the error comes back', async () => {
  const client = new FakePg([{ command: 'SAVEPOINT', fields: [], rows: [] }, Object.assign(new Error('The row id = 1 changed'), { code: 'P0001' }), { command: 'ROLLBACK', fields: [], rows: [] }, { command: 'RELEASE', fields: [], rows: [] }]);
  const s = postgresSession({ name: 'pg', kind: 'postgres' }, client);
  await assert.rejects(s.run('SAVEPOINT trawl_edit;\nDO $$ BEGIN END $$;\nRELEASE SAVEPOINT trawl_edit;', { recover: 'ROLLBACK TO SAVEPOINT trawl_edit;\nRELEASE SAVEPOINT trawl_edit;' }), (e) => e.message === 'The row id = 1 changed' && e.number === 'P0001');
  assert.deepEqual(client.sent, ['SAVEPOINT trawl_edit', 'DO $$ BEGIN END $$', 'ROLLBACK TO SAVEPOINT trawl_edit', 'RELEASE SAVEPOINT trawl_edit']);
});

